-- ADR-030: Auth admin app_metadata is not visible to ordinary INSERT triggers.
--
-- Invitations therefore derive authority only from a server-created, hash-only
-- intent. Exact raw-user-metadata provisioning modes distinguish the benign
-- self-signup path from the invitation path before any tenant write occurs.

begin;

do $$
begin
  if to_regclass('public.tenants') is null
    or to_regclass('public.users') is null
    or to_regclass('public.audit_log') is null
    or to_regprocedure('public.audit_log_trigger()') is null then
    raise exception
      'ADR-030 requires tenants, users, audit_log, and audit_log_trigger() before apply'
      using errcode = '55000';
  end if;
end
$$;

