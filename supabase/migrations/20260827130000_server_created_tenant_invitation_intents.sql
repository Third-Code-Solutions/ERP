-- The token is never persisted. `token_hash` is SHA-256 hex generated by the
-- trusted server from a cryptographically random 256-bit base64url token.
create table public.tenant_invitation_intents (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null
    references public.tenants(id) on delete cascade,
  invited_email varchar(255) not null,
  invited_role public.role not null,
  invited_by uuid not null,
  created_by uuid not null,
  token_hash char(64) not null,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  consumed_by_user_id uuid
    references auth.users(id) on delete restrict,
  revoked_at timestamptz,
  revoked_by uuid,
  revocation_reason text,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  constraint tenant_invitation_intents_tenant_invited_by_fk
    foreign key (tenant_id, invited_by)
    references public.users(tenant_id, id)
    on delete restrict,
  constraint tenant_invitation_intents_tenant_created_by_fk
    foreign key (tenant_id, created_by)
    references public.users(tenant_id, id)
    on delete restrict,
  constraint tenant_invitation_intents_tenant_revoked_by_fk
    foreign key (tenant_id, revoked_by)
    references public.users(tenant_id, id)
    on delete restrict,
  constraint tenant_invitation_intents_inviter_is_creator
    check (invited_by = created_by),
  constraint tenant_invitation_intents_email_normalized
    check (
      invited_email = lower(btrim(invited_email))
      and length(invited_email) between 3 and 255
      and position('@' in invited_email) > 1
    ),
  constraint tenant_invitation_intents_token_hash_hex
    check (token_hash ~ '^[0-9a-f]{64}$'),
  constraint tenant_invitation_intents_expiry_window
    check (
      expires_at > created_at
      and expires_at <= created_at + interval '24 hours'
    ),
  constraint tenant_invitation_intents_consumption_pair
    check (
      (consumed_at is null and consumed_by_user_id is null)
      or (consumed_at is not null and consumed_by_user_id is not null)
    ),
  constraint tenant_invitation_intents_terminal_state
    check (not (consumed_at is not null and revoked_at is not null)),
  constraint tenant_invitation_intents_revocation_actor
    check (
      (revoked_at is null and revoked_by is null and revocation_reason is null)
      or (
        revoked_at is not null
        and revoked_by is not null
        and revocation_reason = btrim(revocation_reason)
        and length(revocation_reason) > 0
      )
    )
);

