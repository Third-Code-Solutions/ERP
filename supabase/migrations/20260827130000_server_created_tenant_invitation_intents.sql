-- Intent identities and terminal transitions are immutable. A server may only
-- revoke an unconsumed intent, and the auth trigger may only consume one.
create function public.enforce_tenant_invitation_intent_transition()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'Tenant invitation intents are append-only'
      using errcode = '55000';
  end if;

  if new.id is distinct from old.id
    or new.tenant_id is distinct from old.tenant_id
    or new.invited_email is distinct from old.invited_email
    or new.invited_role is distinct from old.invited_role
    or new.invited_by is distinct from old.invited_by
    or new.created_by is distinct from old.created_by
    or new.token_hash is distinct from old.token_hash
    or new.expires_at is distinct from old.expires_at
    or new.created_at is distinct from old.created_at then
    raise exception 'Tenant invitation intent identity is immutable'
      using errcode = '55000';
  end if;

  if old.consumed_at is not null or old.revoked_at is not null then
    raise exception 'Tenant invitation intent is already terminal'
      using errcode = '55000';
  end if;

  if new.consumed_at is not null then
    if new.consumed_by_user_id is null
      or new.revoked_at is not null
      or new.revoked_by is not null
      or new.revocation_reason is not null then
      raise exception 'Invalid tenant invitation intent consumption'
        using errcode = '22023';
    end if;
  elsif new.revoked_at is not null then
    if new.revoked_by is null
      or new.revocation_reason is null
      or new.consumed_by_user_id is not null then
      raise exception 'Invalid tenant invitation intent revocation'
        using errcode = '22023';
    end if;
  else
    raise exception 'Tenant invitation intents may only be consumed or revoked'
      using errcode = '55000';
  end if;

  new.updated_at := pg_catalog.clock_timestamp();
  return new;
end;
$$;

revoke all on function public.enforce_tenant_invitation_intent_transition()
  from public, anon, authenticated;
grant execute on function public.enforce_tenant_invitation_intent_transition()
  to service_role;

create trigger tenant_invitation_intents_enforce_transition
  before update or delete on public.tenant_invitation_intents
  for each row execute function public.enforce_tenant_invitation_intent_transition();

-- `audit_log_trigger()` serializes the audit chain. This custom emitter never
-- serializes the intent row, so neither the raw token nor its hash can enter
-- immutable audit evidence.
create function public.audit_tenant_invitation_intent()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_action text;
  v_actor_id uuid;
  v_diff jsonb;
  v_prev_hash text;
  v_created_at timestamptz := pg_catalog.clock_timestamp();
begin
  if tg_op = 'INSERT' then
    v_action := 'intent_created';
    v_actor_id := new.created_by;
    v_diff := pg_catalog.jsonb_build_object(
      'intent_id', new.id,
      'invited_role', new.invited_role::text
    );
  elsif new.consumed_at is distinct from old.consumed_at then
    v_action := 'intent_consumed';
    v_actor_id := new.invited_by;
    v_diff := pg_catalog.jsonb_build_object(
      'intent_id', new.id,
      'auth_user_id', new.consumed_by_user_id
    );
  elsif new.revoked_at is distinct from old.revoked_at then
    v_action := 'intent_revoked';
    v_actor_id := new.revoked_by;
    v_diff := pg_catalog.jsonb_build_object('intent_id', new.id);
  else
    raise exception 'Tenant invitation intent audit transition is invalid'
      using errcode = '55000';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('audit_log:' || new.tenant_id::text, 0)
  );

  select hash
    into v_prev_hash
    from public.audit_log
   where tenant_id = new.tenant_id
   order by id desc
   limit 1;

  if v_prev_hash is null then
    v_prev_hash := 'genesis';
  end if;

  insert into public.audit_log (
    tenant_id,
    actor_id,
    entity_type,
    entity_id,
    entity_key,
    action,
    diff,
    prev_hash,
    hash,
    created_at
  )
  values (
    new.tenant_id,
    v_actor_id,
    'tenant_invitation_intents',
    new.id,
    new.id::text,
    v_action,
    v_diff,
    v_prev_hash,
    pg_catalog.encode(
      extensions.digest(
        v_prev_hash
          || 'tenant_invitation_intents'
          || new.id::text
          || v_action
          || v_created_at::text,
        'sha256'
      ),
      'hex'
    ),
    v_created_at
  );

  return new;
end;
$$;

revoke all on function public.audit_tenant_invitation_intent()
  from public, anon, authenticated;
grant execute on function public.audit_tenant_invitation_intent()
  to service_role;

create trigger audit_tenant_invitation_intents
  after insert or update on public.tenant_invitation_intents
  for each row execute function public.audit_tenant_invitation_intent();

